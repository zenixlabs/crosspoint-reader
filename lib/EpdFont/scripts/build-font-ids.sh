#!/bin/bash

# Error catch safety net to keep window open on failure
catch_exit() {
  echo ""
  echo "--------------------------------------------------"
  echo "Script stopped or failed. Press Enter to close..."
  read
}
trap catch_exit EXIT

set -e

cd "$(dirname "$0")/../builtinFonts"

echo "// The contents of this file are generated by ./lib/EpdFont/scripts/build-font-ids.sh"
echo "#pragma once"
echo ""

# Native helper function to calculate identical Ruby-like 32-bit signed hashes
get_font_id() {
  local total=0
  
  # Determine the available system hash utility
  local hash_cmd=""
  if command -v sha256sum >/dev/null 2>&1; then
    hash_cmd="sha256sum"
  elif command -v openssl >/dev/null 2>&1; then
    hash_cmd="openssl dgst -sha256"
  else
    echo "Error: Neither sha256sum nor openssl found." >&2
    exit 1
  fi

  for file in "$@"; do
    if [ ! -f "$file" ]; then
      echo "Error: File $file not found." >&2
      exit 1
    fi
    
    # Get hex hash (first 64 chars)
    local hex_hash=$($hash_cmd "$file" | head -c 64 | awk '{print $1}')
    
    # Take the last 15 hex digits to safely parse inside Bash's 64-bit int limits
    local truncate_hex=${hex_hash: -15}
    local dec_val=$((16#$truncate_hex))
    
    total=$((total + dec_val))
  done

  # Constrain total to a 32-bit signed integer matching Ruby's logic
  local u32=$(( total & 0xFFFFFFFF ))
  if [ $u32 -ge 2147483648 ]; then
    echo $(( u32 - 4294967296 ))
  else
    echo $u32
  fi
}

echo "#define NOTOSANS_12_FONT_ID ($(get_font_id "./notosans_12_regular.h" "./notosans_12_bold.h" "./notosans_12_bolditalic.h" "./notosans_12_italic.h"))"

echo "#define NOTOSANS_14_FONT_ID ($(get_font_id "./notosans_14_regular.h" "./notosans_14_bold.h" "./notosans_14_bolditalic.h" "./notosans_14_italic.h"))"

echo "#define NOTOSANS_16_FONT_ID ($(get_font_id "./notosans_16_regular.h" "./notosans_16_bold.h" "./notosans_16_bolditalic.h" "./notosans_16_italic.h"))"

echo "#define NOTOSANS_18_FONT_ID ($(get_font_id "./notosans_18_regular.h" "./notosans_18_bold.h" "./notosans_18_bolditalic.h" "./notosans_18_italic.h"))"

echo "#define UI_10_FONT_ID ($(get_font_id "./ubuntu_10_regular.h" "./ubuntu_10_bold.h"))"

echo "#define UI_12_FONT_ID ($(get_font_id "./ubuntu_12_regular.h" "./ubuntu_12_bold.h"))"

echo "#define SMALL_FONT_ID ($(get_font_id "./notosans_8_regular.h"))"

echo "#define CUSTOM1_FONT_ID ($(get_font_id "./custom1.h"))"

FONT_ID_NAMES=(
  CUSTOM1_FONT_ID
  NOTOSANS_12_FONT_ID
  NOTOSANS_14_FONT_ID
  NOTOSANS_16_FONT_ID
  NOTOSANS_18_FONT_ID
  UI_10_FONT_ID
  UI_12_FONT_ID
  SMALL_FONT_ID
)

echo ""
echo "// Font ID 0 is reserved as the \"not found\" sentinel."
echo "// Guard against any hash accidentally producing 0."
for name in "${FONT_ID_NAMES[@]}"; do
  echo "static_assert(${name} != 0, \"Font ID collision with sentinel\");"
done

# Clear the trap so it ends gracefully
trap - EXIT
read
